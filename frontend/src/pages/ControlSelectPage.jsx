export default function ControlSelectPage({ onSelectControls }) {
  const [selected, setSelected] = useState([])
  const [filterCat, setFilterCat] = useState('전체')
  const [openGuideId, setOpenGuideId] = useState(null)
  const navigate = useNavigate()

  const categories = ['전체', ...Array.from(new Set(ISMS_CONTROLS.map(c => c.category)))]

  const filtered = filterCat === '전체'
    ? ISMS_CONTROLS
    : ISMS_CONTROLS.filter(c => c.category === filterCat)

  const toggle = (id) =>
    setSelected(prev => prev.includes(id) ? prev.filter(x => x !== id) : [...prev, id])

  const toggleAll = () => {
    const ids = filtered.map(c => c.control_id)
    const allSel = ids.every(id => selected.includes(id))
    setSelected(prev => allSel
      ? prev.filter(id => !ids.includes(id))
      : Array.from(new Set([...prev, ...ids]))
    )
  }

  const handleNext = () => {
    onSelectControls(ISMS_CONTROLS.filter(c => selected.includes(c.control_id)))
    navigate('/upload')
  }

  const filteredAllSelected = filtered.length > 0 && filtered.every(c => selected.includes(c.control_id))

  return (
    <div className="select-page">
      <div className="page-header" style={{ marginBottom: 16 }}>
        <h2 className="page-title">점검 항목 선택</h2>
        <p className="page-desc">점검할 항목을 선택하세요. 카테고리로 필터링할 수 있습니다.</p>
      </div>

      {/* 카테고리 필터 */}
      <div className="cat-filter-bar">
        {categories.map(cat => {
          const color = cat === '전체' ? '#64748B' : (CATEGORY_COLORS[cat]?.color || '#64748B')
          const selCount = cat === '전체'
            ? selected.length
            : ISMS_CONTROLS.filter(c => c.category === cat && selected.includes(c.control_id)).length
          const total = cat === '전체' ? ISMS_CONTROLS.length : ISMS_CONTROLS.filter(c => c.category === cat).length
          return (
            <button key={cat} className={`cat-tab ${filterCat === cat ? 'active' : ''}`}
              onClick={() => setFilterCat(cat)}>
              {cat !== '전체' && <span className="cat-tab-dot" style={{ background: color }} />}
              {cat}
              {selCount > 0 && <span className="cat-tab-sel">{selCount}</span>}
              <span className="cat-tab-total">/{total}</span>
            </button>
          )
        })}
      </div>

      {/* 툴바 */}
      <div className="list-toolbar">
        <label className="toolbar-check-all">
          <input type="checkbox" checked={filteredAllSelected} onChange={toggleAll} />
          <span>{filteredAllSelected ? '전체 해제' : '전체 선택'}</span>
        </label>
        <span className="toolbar-count">
          <strong>{selected.length}</strong>개 선택됨 / 전체 {filtered.length}개
        </span>
      </div>

      {/* 컴팩트 리스트 */}
      <div className="item-list">
        {filtered.map((ctrl) => {
          const cat = CATEGORY_COLORS[ctrl.category] || { bg: '#F1F5F9', color: '#475569', border: '#E2E8F0' }
          const isSel = selected.includes(ctrl.control_id)
          const guide = CONTROL_GUIDELINES[ctrl.control_id]
          const isGuideOpen = openGuideId === ctrl.control_id
          return (
            <div key={ctrl.control_id}>
              <div className={`item-row ${isSel ? 'item-row-selected' : ''}`}
                onClick={() => toggle(ctrl.control_id)}>
                <div className={`item-check ${isSel ? 'checked' : ''}`}>
                  {isSel && '✓'}
                </div>
                <span className="item-id">{ctrl.control_id}</span>
                <span className="item-cat" style={{ background: cat.bg, color: cat.color, border: `1px solid ${cat.border}` }}>
                  {ctrl.category}
                </span>
                <span className="item-name">{ctrl.control_name}</span>
                {guide && (
                  <button
                    className={`item-guide-btn ${isGuideOpen ? 'item-guide-btn-open' : ''}`}
                    onClick={(e) => { e.stopPropagation(); setOpenGuideId(isGuideOpen ? null : ctrl.control_id) }}
                    title="항목 가이드라인 보기"
                  >
                    ?
                  </button>
                )}
              </div>
              {isGuideOpen && guide && (
                <div className="item-guide-panel">
                  <p className="item-guide-summary">{guide.summary}</p>
                  <div className="item-guide-sections">
                    <div className="item-guide-section">
                      <span className="item-guide-label">주로 확인하는 것</span>
                      <ul className="item-guide-checklist">
                        {guide.checks.map((c, i) => <li key={i}>{c}</li>)}
                      </ul>
                    </div>
                    <div className="item-guide-section">
                      <span className="item-guide-label">필요한 문서</span>
                      <div className="item-guide-tags">
                        {guide.evidence.map((e, i) => <span key={i} className="item-guide-tag">{e}</span>)}
                      </div>
                    </div>
                  </div>
                </div>
              )}
            </div>
          )
        })}
      </div>

      <div style={{ height: 72 }} />

      {/* 하단 액션바 */}
      <div className={`floating-bar ${selected.length > 0 ? 'floating-bar-visible' : ''}`}>
        <div className="floating-bar-inner">
          <div className="floating-bar-info">
            <span className="floating-num">{selected.length}</span>
            <span className="floating-text">개 항목 선택됨</span>
            <span className="floating-sub">전체 62개 중</span>
          </div>
          <div className="floating-bar-actions">
            <button className="btn-secondary floating-clear" onClick={() => setSelected([])}>초기화</button>
            <button className="btn-primary" onClick={handleNext}>증적 업로드로 이동 →</button>
          </div>
        </div>
      </div>
    </div>
  )
}
